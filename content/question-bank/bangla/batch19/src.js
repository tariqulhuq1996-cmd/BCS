const seedPick = (pool, ans, key, n = 3) => {
  const c = pool.filter((p) => p !== ans);
  let k = [...key].reduce((a, ch) => a + ch.charCodeAt(0), 0);
  const out = [];
  while (out.length < n) { const v = c[k % c.length]; if (!out.includes(v)) out.push(v); k += 7; }
  return out;
};
